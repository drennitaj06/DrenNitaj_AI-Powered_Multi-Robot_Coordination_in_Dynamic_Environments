# --------------------------------------------------------------------------- guards


def guard_task(planner: str, seed: int, block: str) -> None:
    """Block D only; RRT\\* only on its 60-seed subset. Raised before any scenario generation."""
    allowed = SEEDS.get(planner)
    if allowed is None:
        raise ValueError(f"planner {planner!r} is not in the Block D design")
    if block != "D" or int(seed) not in allowed:
        raise ValueError(f"seed {seed} / block {block!r} is not allowed for {planner} in Block D "
                         f"({allowed.start}–{allowed.stop - 1})")  # fmt: skip


def worker_check_seeds(seeds: Iterable[int], block: str) -> list[int]:
    """Replacement of ``check_seeds`` in the workers: Block D seeds only."""
    out = [int(s) for s in seeds]
    if block != "D" or any(s not in BLOCK_D for s in out):
        raise ValueError(f"seeds {out[:5]} / block {block!r} are outside Block D (12000–12199)")
    return out


def _init_worker() -> None:
    """Worker initializer (runs inside every worker process, spawned or forked).

    Layer 2: the production ``run_episode`` is wrapped so that the planner-specific
    :func:`guard_task` runs before anything else in it. Layer 3: the production ``check_seeds``
    (called first inside ``run_episode``) is replaced by the Block D-only check. Layer 1 is
    :func:`_run` itself, which calls :func:`guard_task` before the scenario sampler.
    """
    from robocoord.marl import evaluation

    original = evaluation.run_episode
    if not getattr(original, "block_d_guard", False):

        def guarded(task: Any, reward: Any = None) -> dict[str, Any]:
            guard_task(task.planner, task.seed, task.block)
            result: dict[str, Any] = original(task, reward)
            return result

        guarded.block_d_guard = True  # type: ignore[attr-defined]
        setattr(evaluation, "run_episode", guarded)  # noqa: B010 (module global)
    setattr(evaluation, "check_seeds", worker_check_seeds)  # noqa: B010 (module global)


def _run(job: tuple[str, str, Any]) -> dict[str, Any]:
    """One episode; the guard runs first; a failure is recorded (type, message)."""
    from robocoord.marl.evaluation import run_episode
    from robocoord.marl.scenarios import LEVELS as DISTS

    _unit, arm, task = job
    guard_task(task.planner, task.seed, task.block)
    spec = DISTS[task.level].sample(task.seed)
    extra = {"arm": arm, "instance_sha256": selection_block.fingerprint(spec),
             "max_steps": spec.max_steps}  # fmt: skip
    try:
        rec: dict[str, Any] = run_episode(task)
    except Exception as exc:  # every failure is a reported outcome
        rec = {k: v for k, v in asdict(task).items() if k != "checkpoint"}
        rec.update(
            checkpoint=os.path.basename(task.checkpoint) if task.checkpoint else None,
            robots=len(spec.robots),
            status="error",
            error_type=type(exc).__name__,
            error_message=str(exc)[:500],
        )
        return {**rec, **extra}
    return {**rec, **extra, "status": "ok"}


# --------------------------------------------------------------------------- design and checks


def design_from(pk: dict[str, Any]) -> bda.Design:
    runs = pk["runs"]
    return bda.Design(
        pairs={r: {"old": runs[r]["old"], "new": runs[r]["new"]} for r in PAIR_RUNS},
        unchanged={r: runs[r]["new"] for r in UNCHANGED_RUNS},
    )


def picks() -> dict[str, Any]:
    """Checkpoint identities and integrity (protocol §3). Read-only."""
    sel_path = block_c.SELECTIONS
    sel = json.loads(sel_path.read_text("utf-8"))
    out: dict[str, Any] = {"runs": {}, "notes": []}
    ok = sha256(sel_path) == SELECTIONS_SHA256
    if not ok:
        out["notes"].append("selections.json differs from the recorded SCB-C v5 output")
    for p in block_c.SCBC_CODE:
        if sel["code"][p] != sha256(Path(p)):
            ok = False
            out["notes"].append(f"{p} changed since the SCB-C v5 selection")
    s_hashes = json.loads(BLOCK_S_MANIFEST.read_text("utf-8"))["checkpoints"]
    c_hashes = json.loads(BLOCK_C_MANIFEST.read_text("utf-8"))["checkpoints_before"]
    for run in (*PAIR_RUNS, *UNCHANGED_RUNS):
        root = Path(f"results/training/{run}")
        best = json.loads((root / "best.json").read_text("utf-8"))
        old = f"step_{int(best['env_steps']):08d}.pt"
        new = sel["runs"][run]["selected"]
        side = json.loads(ckpt(run, old).with_suffix(".json").read_text("utf-8"))
        meta_diff = sorted(k for k in set(best) | set(side)
                           if k not in block_c.SIDECAR_FILE_FIELDS and best.get(k) != side.get(k))  # fmt: skip
        h_old, h_new, h_best = (
            sha256(ckpt(run, old)),
            sha256(ckpt(run, new)),
            sha256(root / "best.pt"),
        )
        new_key = str(ckpt(run, new)).replace("\\", "/")
        checks = {
            "best_pt_intact": h_best == best["sha256"],
            "step_file_hash_matches_its_sidecar": h_old == side["sha256"],
            "best_pt_tensors_identical_to_step_file": block_c.same_weights(root / "best.pt",
                                                                           ckpt(run, old)),
            "sidecar_metadata_identical": not meta_diff,
            "new_hash_equals_block_s_manifest": s_hashes.get(new_key) == h_new,
            "pick_changed_as_designed": (old != new) == (run in PAIR_RUNS),
        }  # fmt: skip
        if run in PAIR_RUNS:
            checks["hashes_equal_block_c_manifest"] = (
                c_hashes.get(str(ckpt(run, old)).replace("\\", "/")) == h_old
                and c_hashes.get(new_key) == h_new
            )
        ok &= all(checks.values())
        out["runs"][run] = {"old": old, "new": new, "issue6_env_steps": best["env_steps"],
                            "sha256": {"old": h_old, "new": h_new, "best.pt": h_best},
                            "checks": checks, "sidecar_differences": meta_diff}  # fmt: skip
    out["selections_sha256"] = sha256(sel_path)
    out["ok"] = ok
    return out


def frozen_hashes() -> dict[str, str]:
    return {str(p).replace("\\", "/"): sha256(p) for p in FROZEN}


def _require_freeze(out: Path) -> dict[str, Any]:
    path = out / "plan_freeze.json"
    if not path.exists():
        raise SystemExit("the protocol is not frozen; refusing")
    freeze: dict[str, Any] = json.loads(path.read_text("utf-8"))
    if freeze["hashes"] != frozen_hashes():
        raise SystemExit("protocol / runner / analysis changed since the freeze; refusing")
    return freeze


#: Selection artifacts recorded (read only) in the freeze manifest.
ARTIFACTS = (block_c.SELECTIONS, BLOCK_C_CHECK, BLOCK_C_MANIFEST, BLOCK_S_MANIFEST)


def freeze_manifest() -> dict[str, Any]:
    """Everything the freeze records. Read only: hashes files and checkpoints, writes nothing,
    generates no scenario."""
    sel = json.loads(block_c.SELECTIONS.read_text("utf-8"))
    scbc = {p: {"recorded": sel["code"][p], "current": sha256(Path(p))} for p in block_c.SCBC_CODE}
    cks: dict[str, str] = {}
    for run in (*PAIR_RUNS, *UNCHANGED_RUNS):
        root = Path(f"results/training/{run}")
        best = json.loads((root / "best.json").read_text("utf-8"))
        names = {f"step_{int(best['env_steps']):08d}.pt", sel["runs"][run]["selected"]}
        for p in (root / "best.pt", root / "best.json", *(ckpt(run, n) for n in sorted(names))):
            cks[str(p).replace("\\", "/")] = sha256(p)
    return {
        "hashes": frozen_hashes(),
        "scbc_code_matches_selections": all(v["recorded"] == v["current"] for v in scbc.values()),
        "selections_matches_recorded": sha256(block_c.SELECTIONS) == SELECTIONS_SHA256,
        "scbc_code": scbc,
        "selection_artifacts": {str(p).replace("\\", "/"): sha256(p) for p in ARTIFACTS},
        "checkpoints": cks,
        "environment": _env(),
    }


def freeze(out: Path) -> dict[str, Any]:
    for name in ("check.json", "records.jsonl"):
        if (out / name).exists():
            raise SystemExit(f"{name} exists; the freeze must precede the formal execution")
    bda.verify_frozen_dependency()
    man = freeze_manifest()
    if not man["scbc_code_matches_selections"]:
        raise SystemExit("SCB-C code differs from the hashes recorded in selections.json")
    if not man["selections_matches_recorded"]:
        raise SystemExit("selections.json differs from the recorded SCB-C v5 output")
    rep = {"frozen_at": dt.datetime.now().isoformat(timespec="seconds"), **man}
    out.mkdir(parents=True, exist_ok=True)
    (out / "plan_freeze.json").write_text(json.dumps(rep, indent=1), "utf-8")
    return rep


def scan_results(out: Path, block: range = BLOCK_D) -> tuple[int, dict[str, int]]:
    """Stored result files with a seed field in ``block`` (the output folder excluded)."""
    pat = re.compile(rb'"seed": ?(\d{1,6})\b')
    hits: dict[str, int] = {}
    scanned = 0
    for p in Path("results").rglob("*"):
        if not p.is_file() or p.suffix not in (".json", ".jsonl", ".csv"):
            continue
        if out.resolve() in p.resolve().parents:
            continue
        scanned += 1
        for m in pat.finditer(p.read_bytes()):
            if int(m.group(1)) in block:
                hits[str(p)] = hits.get(str(p), 0) + 1
    return scanned, hits


def stored_training_instance_hashes() -> set[str]:
    """Scenario-instance hashes stored by training, if any (read only; nothing regenerated)."""
    found: set[str] = set()
    pat = re.compile(rb'"instance_sha256": ?"([0-9a-f]{64})"')
    for p in Path("results/training").rglob("*.jsonl"):
        found.update(m.group(1).decode() for m in pat.finditer(p.read_bytes()))
    return found


def fingerprints(block: Iterable[int]) -> dict[str, list[str]]:
    """Instance hashes per level. The only scenario-generation call of the check."""
    from robocoord.marl.scenarios import LEVELS as DISTS

    seeds = list(block)
    for s in seeds:
        for name, r in FORBIDDEN.items():
            if s in r:
                raise ValueError(f"{name} seed {s} must not be generated here")
    return {lvl: [selection_block.fingerprint(DISTS[lvl].sample(s)) for s in seeds]
            for lvl in LEVELS}  # fmt: skip


def check(out: Path) -> dict[str, Any]:
    _require_freeze(out)
    bda.verify_frozen_dependency()
    if (out / "records.jsonl").exists():
        raise SystemExit("records exist; the check precedes the run")
    for name, r in {**COMPARE_WITH, **FORBIDDEN}.items():
        assert not set(r) & set(BLOCK_D), name
    scanned, hits = scan_results(out)
    train = stored_training_instance_hashes()
    pk = picks()
    other = {b: fingerprints(r) for b, r in COMPARE_WITH.items()}
    stored_c = json.loads(BLOCK_C_CHECK.read_text("utf-8"))["fingerprints"]
    fd = fingerprints(BLOCK_D)  # the first Block D generation of the formal execution
    rep: dict[str, Any] = {
        "block_d": [BLOCK_D.start, BLOCK_D.stop - 1],
        "block_d_rrtstar": [BLOCK_D_RRT.start, BLOCK_D_RRT.stop - 1],
        "files_scanned": scanned,
        "files_with_block_d_seeds": hits,
        "unique_instances_in_D": {lvl: len(set(v)) for lvl, v in fd.items()},
        "overlap_with": {
            lvl: {b: len(set(fd[lvl]) & set(other[b][lvl])) for b in other} for lvl in LEVELS
        },
        "block_c_regenerated_equals_stored": other["C"] == stored_c,
        "training_disjointness": (
            {"verified": True, "overlap": sum(len(set(v) & train) for v in fd.values())}
            if train
            else {
                "verified": False,
                "reason": "no scenario-instance hashes are stored for training; "
                "training scenarios were not regenerated (protocol §8)",
            }
        ),
        "previous_in_memory_generations": "two earlier disjointness checks (proposal revision "
        "2, static level; L1 follow-up selection_block.check, all levels) generated Block D "
        "instances in memory and stored overlap counts only (protocol §8)",
        "picks": pk,
        "fingerprints": fd,
    }
    rep["ok"] = bool(
        not hits
        and pk["ok"]
        and rep["block_c_regenerated_equals_stored"]
        and all(n == len(BLOCK_D) for n in rep["unique_instances_in_D"].values())
        and all(x == 0 for v in rep["overlap_with"].values() for x in v.values())
        and (not train or rep["training_disjointness"]["overlap"] == 0)
    )
    return rep


# --------------------------------------------------------------------------- tasks and run


def tasks(design: bda.Design) -> list[tuple[str, str, Any]]:
    """All 8 220 jobs, interleaved seed by seed (then level) across every arm."""
    from robocoord.marl.evaluation import EvalTask

    jobs: list[tuple[str, str, Any]] = []
    for s in BLOCK_D:
        for lvl in LEVELS:
            for planner in ("astar", "rrtstar"):
                if s not in SEEDS[planner]:
                    continue
                for unit, arm in design.units(planner):
                    if unit == BASELINE:
                        t = EvalTask("baseline-noresolver", lvl, s, planner, "D", None, label=unit)
                    else:
                        name = (
                            design.pairs[unit][arm]
                            if arm in bda.PAIR_ARMS
                            else design.unchanged[unit]
                        )
                        t = EvalTask("ppo", lvl, s, planner, "D", str(ckpt(unit, name)), label=unit)
                    jobs.append((unit, arm, t))
    return jobs


def _key(job: tuple[str, str, Any]) -> tuple[str, str, str, str, int]:
    unit, arm, t = job
    return (t.planner, unit, arm, t.level, t.seed)


def _rkey(r: dict[str, Any]) -> tuple[str, str, str, str, int]:
    return (r["planner"], r["label"], r["arm"], r["level"], r["seed"])


def _records(path: Path) -> list[dict[str, Any]]:
    with open(path, encoding="utf-8") as fh:
        return [json.loads(line) for line in fh]


def history_snapshot(out: Path) -> dict[str, str]:
    """SHA-256 of every file under ``results/`` (output folder excluded) and ``docs/``."""
    snap: dict[str, str] = {}
    for root in (Path("results"), Path("docs")):
        for p in sorted(root.rglob("*")):
            if p.is_file() and out.resolve() not in p.resolve().parents:
                snap[str(p).replace("\\", "/")] = sha256(p)
    return snap


def _env() -> dict[str, str]:
    import numpy
    import torch

    return {"python": platform.python_version(), "numpy": numpy.__version__,
            "torch": torch.__version__, "platform": platform.platform()}  # fmt: skip


def run(out: Path, workers: int) -> int:
    freeze_rep = _require_freeze(out)
    rep = json.loads((out / "check.json").read_text("utf-8"))
    if not rep["ok"]:
        raise SystemExit("pre-run check failed; not running")
    design = design_from(rep["picks"])
    jobs = tasks(design)
    rec_path = out / "records.jsonl"
    done = {_rkey(r) for r in _records(rec_path)} if rec_path.exists() else set()
    todo = [j for j in jobs if _key(j) not in done]
    cks = sorted({t.checkpoint for _, _, t in jobs if t.checkpoint})
    before = {c.replace("\\", "/"): sha256(Path(c)) for c in cks}
    hist_path = out / "history_before.json"
    if not hist_path.exists():
        hist_path.write_text(json.dumps(history_snapshot(out), indent=0), "utf-8")
    t0 = time.perf_counter()
    with (
        open(rec_path, "a", encoding="utf-8") as fh,
        ProcessPoolExecutor(max_workers=workers, initializer=_init_worker) as pool,
    ):
        for i, rec in enumerate(pool.map(_run, todo, chunksize=2), 1):
            fh.write(json.dumps(rec) + "\n")
            if i % 400 == 0:
                fh.flush()
                el = time.perf_counter() - t0
                print(f"{i}/{len(todo)} {el:.0f}s", flush=True)  # progress only, no outcomes
    after = {c.replace("\\", "/"): sha256(Path(c)) for c in cks}
    hist_after = history_snapshot(out)
    hist_before = json.loads(hist_path.read_text("utf-8"))
    man_path = out / "manifest.json"
    manifest: dict[str, Any] = (
        json.loads(man_path.read_text("utf-8"))
        if man_path.exists()
        else {"block_d": [BLOCK_D.start, BLOCK_D.stop - 1], "episodes": len(jobs),
              "frozen": freeze_rep, "invocations": []}
    )  # fmt: skip
    manifest["invocations"].append(
        {
            "started": dt.datetime.now().isoformat(timespec="seconds"),
            "episodes": len(todo),
            "wall_s": time.perf_counter() - t0,
            "workers": workers,
        }
    )
    manifest.update(
        checkpoints_before=before,
        checkpoints_after=after,
        checkpoints_unchanged=before == after,
        history_unchanged=hist_after == hist_before,
        code={p: sha256(Path(p)) for p in CODE},
        environment=_env(),
    )
    man_path.write_text(json.dumps(manifest, indent=1), "utf-8")
    n = len(_records(rec_path))
    print(
        f"records: {n} / {len(jobs)}; checkpoints unchanged: {before == after}; "
        f"history unchanged: {hist_after == hist_before}"
    )
    return 0 if n == len(jobs) and before == after and hist_after == hist_before else 1


def replay(out: Path, workers: int) -> dict[str, Any]:
    _require_freeze(out)
    design = design_from(json.loads((out / "check.json").read_text("utf-8"))["picks"])
    jobs = tasks(design)[::REPLAY_STRIDE]
    stored = {_rkey(r): r for r in _records(out / "records.jsonl")}
    with ProcessPoolExecutor(max_workers=workers, initializer=_init_worker) as pool:
        fresh = list(pool.map(_run, jobs))
    diffs = []
    for job, r in zip(jobs, fresh, strict=True):
        s = stored[_key(job)]
        bad = sorted(k for k in set(r) | set(s) if k not in bda.TIMING and r.get(k) != s.get(k))
        if bad:
            diffs.append({"key": list(_key(job)), "fields": bad})
    return {"stride": REPLAY_STRIDE, "episodes": len(jobs), "identical": len(jobs) - len(diffs),
            "differences": diffs, "ignored_fields": list(bda.TIMING)}  # fmt: skip


def pairing(records: list[dict[str, Any]], design: bda.Design) -> dict[str, Any]:
    """Episode-level pair checks for D1 and D3 (2 400 + 720 = 3 120 episode pairs; the analysis
    unit is the seed: 4 × 200 + 4 × 60 = 1 040 paired seed units)."""
    by = {_rkey(r): r for r in records}
    out: dict[str, Any] = {}
    for planner in ("astar", "rrtstar"):
        n = same = 0
        for run in design.pairs:
            for lvl in LEVELS:
                for s in SEEDS[planner]:
                    a, b = (by.get((planner, run, arm, lvl, s)) for arm in bda.PAIR_ARMS)
                    if a is None or b is None:
                        continue
                    n += 1
                    same += all(a.get(k) == b.get(k) for k in bda.PAIRED)
        out[planner] = {"episode_pairs": n, "expected": len(design.pairs) * 3 * len(SEEDS[planner]),
                        "identical_paired_fields": same,
                        "seed_units": len(design.pairs) * len(SEEDS[planner])}  # fmt: skip
    return out


def analyse(out: Path) -> dict[str, Any]:
    freeze_rep = _require_freeze(out)
    bda.verify_frozen_dependency()
    rep = json.loads((out / "check.json").read_text("utf-8"))
    design = design_from(rep["picks"])
    records = _records(out / "records.jsonl")
    fps = {lvl: dict(zip(BLOCK_D, v, strict=True)) for lvl, v in rep["fingerprints"].items()}
    data = bda.build(records, design, fps)
    res = bda.analyse(data)
    res["descriptives"] = bda.descriptives(records, design)
    res["pairing"] = pairing(records, design)
    res["frozen_hashes"] = freeze_rep["hashes"]
    res["records_sha256"] = sha256(out / "records.jsonl")
    return res


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=("freeze", "check", "run", "replay", "analyse"))
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--workers", type=int, default=max(1, (os.cpu_count() or 2) - 2))
    ap.add_argument("--authorized-freeze", action="store_true")
    ap.add_argument("--authorized-block-d", action="store_true")
    args = ap.parse_args(argv)
    if args.cmd == "freeze":
        if not args.authorized_freeze:
            raise SystemExit("freeze needs --authorized-freeze (separate approval)")
        print(json.dumps(freeze(args.out), indent=1))
        return 0
    if args.cmd in ("check", "run", "replay") and not args.authorized_block_d:
        raise SystemExit(f"{args.cmd} accesses Block D and needs --authorized-block-d")
    if args.cmd == "check":
        rep = check(args.out)
        (args.out / "check.json").write_text(json.dumps(rep, indent=1), "utf-8")
        print(json.dumps({k: v for k, v in rep.items() if k != "fingerprints"}, indent=1))
        return 0 if rep["ok"] else 1
    if args.cmd == "run":
        return run(args.out, args.workers)
    if args.cmd == "replay":
        r = replay(args.out, args.workers)
        (args.out / "replay.json").write_text(json.dumps(r, indent=1), "utf-8")
        print(json.dumps(r, indent=1))
        return 0 if not r["differences"] else 1
    res = analyse(args.out)
    (args.out / "analysis.json").write_text(json.dumps(res, indent=1), "utf-8")
    print(json.dumps({"usable": res["usable"], "pairing": res["pairing"]}, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
