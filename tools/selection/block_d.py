"""Block D final evaluation of H-L1 — the isolated runner (Issue 6A; protocol revision 2).

Protocol: ``docs/research/2026-11-21-block-d-protocol.md``; analysis: ``block_d_analysis.py``.

Experiment matrix (8 220 episodes; greedy, auction, shield off, existing configuration):

* D1 — mappo_seed1–3, ippo_seed1 × {old (Issue #6 pick), new (SCB-C v5 pick)}, A\\*,
  seeds 12 000–12 199 × 3 levels: 4 800;
* D2 — ippo_seed2, ippo_seed3 (pick unchanged), A\\*, the same 600 instances: 1 200;
* D3 — the D1 pairs on RRT\\*, seeds 12 000–12 059 × 3 levels: 1 440;
* D4 — the matched baseline (``baseline-noresolver``), A\\* 600 + RRT\\* 180: 780.

Commands, in the approved order — each needs its own explicit authorization flag::

    python tools/selection/block_d.py freeze  --out results/dev6a/block_d --authorized-freeze
    python tools/selection/block_d.py check   --out results/dev6a/block_d --authorized-block-d
    python tools/selection/block_d.py run     --out results/dev6a/block_d --authorized-block-d
    python tools/selection/block_d.py replay  --out results/dev6a/block_d --authorized-block-d
    python tools/selection/block_d.py analyse --out results/dev6a/block_d

* ``freeze`` hashes the protocol, this file, the analysis module and the reused frozen files.
  It refuses once ``check.json`` or ``records.jsonl`` exists, so the freeze precedes the first
  scenario generation of the formal Block D execution.
* ``check`` (the first Block D scenario generation of the formal execution) refuses unless the
  freeze hashes still match. It scans ``results/`` for Block D seeds; reports whether stored
  training-instance hashes exist (none are stored, so disjointness from training instances is
  reported as **not verified**); hashes the 600 Block D instances and checks that they are unique
  per level and differ from every A, B, C and S instance; and verifies every checkpoint.
* ``run`` refuses unless ``check`` passed and the freeze hashes match. The workers' seed guard
  accepts Block D only (RRT\\*: 12 000–12 059 only) and is applied before the scenario
  generator is called. Tasks are interleaved seed by seed across arms. Failures are recorded,
  not raised; an interrupted run resumes deterministically. Checkpoint and historical-file
  hashes are compared before and after.
* ``replay`` re-runs every 60th task in fresh processes and compares every non-timing field.
* ``analyse`` applies the gate and the pre-specified analysis.

No training, no checkpoint written, nothing moved into ``models/``, no production file changed.
"""

